function arg(name, fallback = '') {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
}

function c(stream, slug, brief) {
  return {
    key: `aggressive-s1-${slug}`,
    concept: slug,
    brief,
    family: stream,
    classification: 'MANUS_WORTHY',
    status: 'pending',
    qa_status: null,
  };
}

function sh(id, title, format, cells) {
  return { id, title, format, cells };
}

function grid16(stream, title, rows) {
  if (rows.length !== 16) throw new Error(`${title} wants 16 cells, got ${rows.length}`);
  return sh(title.replace(/\s+/g, '-').slice(0, 24), title, 'black-contact-4x4', rows.map(([slug, brief]) => c(stream, slug, brief)));
}

export function filterSafety(cells) {
  const kept = [];
  const skipped = [];
  for (const cell of cells) {
    const hay = [cell.key, cell.concept, cell.brief].join(' ').toLowerCase();
    const hit = [...SAFETY_SKIP_KEYS].find((deny) => new RegExp(`(^|[^a-z0-9])${deny}([^a-z0-9]|$)`).test(hay));
    if (hit) skipped.push({ key: cell.key, reason: `MANUS_SAFETY_DENY:${hit}` });
    else kept.push(cell);
  }
  return { kept, skipped };
}

