/**
 * Drop before bank write — mirrors discovery needsReview (abstract / multi-sense /
 * incomplete lemmas). Keeps reseeds from reintroducing junk; live banks are still
 * gated by asset-gap-discovery failsHeuristics until the next seed run.
 */
const SEED_DENY = new Set([
  'orbit', 'thunder', 'herd', 'flock', 'orchestra', 'customs', 'duty-free',
  'magma', 'sediment', 'eruption', 'itinerary', 'molecule', 'atom',
  // glaze + yeast stay seedable (picturable still-lifes)
  'specimen', 'artifact', 'relic', 'constellation',
  'ash cloud', 'periodic table',
  'plane', 'press', 'mold', 'last', 'bit', 'file', 'square',
  'phillips', 'sleeper', 'coupling',
  'vent', 'fault', 'core', 'mantle', 'crust', 'hide', 'pattern', 'signal',
]);

function c(word, usefulness = 0.7, picturable = 0.9, hardToSubstitute = 0.5, tags = []) {
  return { word, usefulness, picturable, hardToSubstitute, tags };
}

function filterSeedConcepts(concepts) {
  return concepts.filter((row) => row?.word && !SEED_DENY.has(String(row.word).toLowerCase()));
}

/** Expand base nouns with ESL-friendly part / tool / place variants. */
function expandParts(base, parts, defaults = {}) {
  const { u = 0.65, p = 0.92, h = 0.55, tag = 'part' } = defaults;
  return parts.map((part) => c(part, u, p, h, [tag, base]));
}

