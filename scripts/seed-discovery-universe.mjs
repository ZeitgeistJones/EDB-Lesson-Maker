function writeDomains() {
  fs.mkdirSync(OUT, { recursive: true });
  for (const d of DOMAINS) {
    const concepts = filterSeedConcepts(d.concepts);
    const payload = { ...d, concepts };
    const file = path.join(OUT, `${d.id}.json`);
    fs.writeFileSync(file, JSON.stringify(payload, null, 2) + '\n');
    const dropped = d.concepts.length - concepts.length;
    const dropNote = dropped ? `, dropped ${dropped} deny` : '';
    console.log(
      `wrote ${path.relative(ROOT, file)} (${d.topics.length} topics, ${concepts.length} concepts${dropNote})`
    );
  }
  const meta = {
    version: 1,
    generatedBy: 'scripts/seed-discovery-universe.mjs',
    domainCount: DOMAINS.length,
    crossTemplates: CROSS_TEMPLATES,
    note: 'Pack-blind discovery banks. Not auto-merged into esl-picturable-source.json.',
  };
  fs.writeFileSync(path.join(OUT, '_meta.json'), JSON.stringify(meta, null, 2) + '\n');
  console.log(`wrote _meta.json (${DOMAINS.length} domains)`);
}

writeDomains();
