/* buildLessonPdf.js
 * Builds a slide-style ESL lesson PDF using jsPDF.
 * Each page is designed like a presentation slide — colored backgrounds,
 * rounded cards, large readable text — optimised for ClassIn's document
 * viewer where the teacher advances pages to pace the lesson.
 *
 * Requires global: jspdf (loaded via CDN <script> tag)
 */

// ── Palette (RGB arrays) ────────────────────────────────────────────
const C = {
  blue:       [59, 130, 246],
  navy:       [30, 58, 95],
  navyLight:  [55, 82, 120],
  coral:      [255, 107, 107],
  yellow:     [255, 217, 61],
  green:      [52, 211, 153],
  lavender:   [238, 240, 255],
  warmYellow: [255, 249, 219],
  peach:      [255, 240, 240],
  mint:       [224, 255, 244],
  white:      [255, 255, 255],
  dark:       [30, 41, 59],
  gray:       [100, 116, 139],
  lightGray:  [241, 245, 249],
  purple:     [139, 92, 246],
};

// Landscape A4 in mm
const W = 297;
const H = 210;
const M = 20; // margin

// Accent-dot colours cycled for lists
const DOTS = [C.coral, C.yellow, C.green, C.blue, C.purple];
// Card backgrounds cycled for vocab / activity lists
const CARDS = [C.lavender, C.warmYellow, C.mint, C.peach];

// ── Helpers ─────────────────────────────────────────────────────────

function fill(doc, rgb) { doc.setFillColor(...rgb); }
function ink(doc, rgb) { doc.setTextColor(...rgb); }
function stroke(doc, rgb) { doc.setDrawColor(...rgb); }

function card(doc, x, y, w, h, rgb, r) {
  fill(doc, rgb);
  doc.roundedRect(x, y, w, h, r ?? 4, r ?? 4, 'F');
}

function bg(doc, rgb) {
  fill(doc, rgb);
  doc.rect(0, 0, W, H, 'F');
}

function deco(doc, cx, cy, r, rgb, opacity) {
  const gs = new doc.GState({ opacity });
  doc.saveGraphicsState();
  doc.setGState(gs);
  fill(doc, rgb);
  doc.circle(cx, cy, r, 'F');
  doc.restoreGraphicsState();
}

function strip(s) {
  return s.replace(/[\u{1F000}-\u{1FFFF}\u{2600}-\u{27BF}\u{FE00}-\u{FE0F}\u{200D}\u{20E3}\u{E0020}-\u{E007F}]/gu, '').trim();
}

function drawText(doc, text, x, y, maxW, opts = {}) {
  const {
    size = 14, bold = false, italic = false, color = C.dark,
    align = 'left', lineH = null,
  } = opts;

  const style = bold && italic ? 'bolditalic' : bold ? 'bold' : italic ? 'italic' : 'normal';
  doc.setFont('helvetica', style);
  doc.setFontSize(size);
  ink(doc, color);

  const cleaned = strip(text);
  const lines = doc.splitTextToSize(cleaned, maxW);
  const lh = lineH ?? size * 0.45;

  const xPos = align === 'center' ? x + maxW / 2 : x;
  doc.text(lines, xPos, y, { align, maxWidth: maxW, lineHeightFactor: 1.35 });

  return y + lines.length * lh;
}

function sectionHeader(doc, label, accentRgb) {
  card(doc, M, M, W - 2 * M, 18, accentRgb ?? C.navy, 5);
  drawText(doc, label, M, M + 12, W - 2 * M, {
    size: 22, bold: true, color: C.white, align: 'center',
  });
}

// ── Page builders ───────────────────────────────────────────────────

function pageTitleSlide(doc, lesson, meta) {
  bg(doc, C.blue);
  deco(doc, -10, -10, 50, C.navy, 0.25);
  deco(doc, W + 10, H + 10, 60, C.navy, 0.20);
  deco(doc, W - 40, 30, 35, C.navy, 0.15);

  drawText(doc, lesson.title, M, 70, W - 2 * M, {
    size: 38, bold: true, color: C.white, align: 'center',
  });

  const sub = `${meta.level}  //  ${meta.duration}-Minute Lesson`;
  drawText(doc, sub, M, 95, W - 2 * M, {
    size: 16, italic: true, color: C.white, align: 'center',
  });

  drawText(doc, 'Generated by Lesson Board Builder', M, H - 16, W - 2 * M, {
    size: 9, color: [180, 210, 255], align: 'center',
  });
}

function pageWarmUp(doc, lesson) {
  bg(doc, C.white);
  sectionHeader(doc, 'Warm Up', C.coral);

  const qY = 50;
  card(doc, M + 8, qY, W - 2 * M - 16, 50, C.lavender, 6);
  drawText(doc, lesson.warmUp.question, M + 16, qY + 20, W - 2 * M - 32, {
    size: 24, bold: true, color: C.navy, align: 'center',
  });

  const aY = 115;
  drawText(doc, 'Sample Answer:', M + 16, aY, W - 2 * M - 32, {
    size: 12, bold: true, color: C.gray,
  });
  card(doc, M + 8, aY + 6, W - 2 * M - 16, 36, C.peach, 5);
  drawText(doc, lesson.warmUp.sampleAnswer, M + 16, aY + 22, W - 2 * M - 32, {
    size: 18, italic: true, bold: true, color: C.coral, align: 'center',
  });

  drawText(doc, 'Let the student answer first before looking at the sample.', M, H - 16, W - 2 * M, {
    size: 9, italic: true, color: C.gray, align: 'center',
  });
}

function maxBoardVocab() {
  return (typeof window !== 'undefined' && window.VocabArt && window.VocabArt.MAX_BOARD_VOCAB) || 6;
}

async function pagesVocabulary(doc, lesson) {
  // Same ceiling + art-preferred order as board cards (adapt mutates in place).
  if (window.VocabArt && typeof window.VocabArt.adaptBoardVocabulary === 'function') {
    try {
      window.VocabArt.adaptBoardVocabulary(lesson, { seed: (lesson && lesson.title) || '' });
    } catch (_) { /* cold icons — fall through to raw slice */ }
  }
  const vocab = (lesson.vocabulary || []).slice(0, maxBoardVocab());

  bg(doc, C.white);
  sectionHeader(doc, 'New Words', C.purple);

  const cols = 2;
  const colW = (W - 2 * M - 12) / cols;
  const perCol = Math.ceil(vocab.length / cols);
  const cardH = Math.min(28, (H - 60) / perCol - 6);

  for (let i = 0; i < vocab.length; i++) {
    const v = vocab[i];
    const col = i < perCol ? 0 : 1;
    const row = i % perCol;
    const x = M + col * (colW + 12);
    const y = 48 + row * (cardH + 6);
    card(doc, x, y, colW, cardH, CARDS[i % CARDS.length], 4);

    let textX = x + 8;
    if (window.VocabIcons) {
      const png = await window.VocabIcons.loadPng(v.word);
      if (png) {
        const iconMm = Math.min(16, cardH - 6);
        const dataUrl = uint8ToPngDataUrl(png);
        doc.addImage(dataUrl, 'PNG', x + 6, y + (cardH - iconMm) / 2, iconMm, iconMm);
        textX = x + 8 + iconMm + 4;
      }
    }

    drawText(doc, v.word, textX, y + cardH / 2 + 2, colW - (textX - x) - 8, {
      size: 20, bold: true, color: C.dark,
    });
  }

  drawText(doc, 'Say each word. Have the student repeat.', M, H - 16, W - 2 * M, {
    size: 9, italic: true, color: C.gray, align: 'center',
  });

  doc.addPage([W, H]);
  bg(doc, C.white);
  sectionHeader(doc, 'New Words \u2014 In Sentences', C.purple);

  const cardH2 = Math.min(34, (H - 56) / perCol - 5);

  vocab.forEach((v, i) => {
    const col = i < perCol ? 0 : 1;
    const row = i % perCol;
    const x = M + col * (colW + 12);
    const y = 46 + row * (cardH2 + 5);
    card(doc, x, y, colW, cardH2, CARDS[i % CARDS.length], 4);
    drawText(doc, v.word, x + 8, y + 11, colW - 16, {
      size: 15, bold: true, color: C.dark,
    });
    drawText(doc, v.sentence, x + 8, y + 22, colW - 16, {
      size: 11, italic: true, color: C.gray,
    });
  });

  drawText(doc, 'Read each example, then ask the student to make their own sentence.', M, H - 16, W - 2 * M, {
    size: 9, italic: true, color: C.gray, align: 'center',
  });
}

function uint8ToPngDataUrl(u8) {
  let bin = '';
  const chunk = 0x8000;
  for (let i = 0; i < u8.length; i += chunk) {
    bin += String.fromCharCode.apply(null, u8.subarray(i, i + chunk));
  }
  return 'data:image/png;base64,' + btoa(bin);
}

function pageSentenceFrames(doc, lesson) {
  bg(doc, C.navy);
  sectionHeader(doc, 'Sentence Frames', C.purple);

  const frames = lesson.sentenceFrames.slice(0, 6);
  const gap = Math.min(24, (H - 70) / frames.length);

  frames.forEach((f, i) => {
    const y = 55 + i * gap;
    fill(doc, DOTS[i % DOTS.length]);
    doc.circle(M + 8, y, 4, 'F');
    drawText(doc, f, M + 20, y + 3, W - 2 * M - 28, {
      size: 20, bold: true, color: C.white,
    });
  });

  drawText(doc, 'Model each frame, then have the student fill in the blank.', M, H - 16, W - 2 * M, {
    size: 9, italic: true, color: [140, 170, 210], align: 'center',
  });
}

// ── Story scene visuals (simple themed panel + emoji, no characters) ─

function drawSceneVisual(doc, x, y, w, h, theme, caption) {
  const t = String(theme || 'nature').toLowerCase();
  const fillRgb = t === 'beach' ? [186, 230, 253]
    : t === 'school' ? [221, 214, 254]
    : t === 'kitchen' || t === 'home' ? [254, 215, 170]
    : t === 'city' ? [203, 213, 225]
    : t === 'sports' ? [187, 247, 208]
    : [254, 243, 199];
  card(doc, x, y, w, h, fillRgb, 6);

  const emoji = t.includes('beach') ? '🏖️'
    : t.includes('school') ? '🏫'
    : t.includes('kitchen') || t.includes('home') ? '🏠'
    : t.includes('city') ? '🏙️'
    : t.includes('sport') ? '⚽'
    : t.includes('park') ? '🌳'
    : '📖';

  drawText(doc, emoji, x, y + h / 2 - 4, w, {
    size: 36, align: 'center',
  });

  const label = String(caption || theme || 'Scene').slice(0, 28);
  fill(doc, C.navy);
  doc.roundedRect(x + 6, y + h - 22, w - 12, 14, 3, 3, 'F');
  drawText(doc, label, x + 8, y + h - 12, w - 16, {
    size: 8, bold: true, color: C.white, align: 'center',
  });
}

function pagesStory(doc, lesson) {
  const story = lesson.story || {};
  // Keep in step with EdbActivities.MAX_STORY_PAGES.
  const pages = (story.pages || []).slice(0, 3);

  pages.forEach((page, i) => {
    if (i > 0) doc.addPage([W, H]);
    bg(doc, C.white);
    const header = i === 0
      ? `Story: ${story.title || 'Let\'s Read!'}`
      : `Story (cont.): ${page.heading || story.title || 'Part 2'}`;
    sectionHeader(doc, header, C.coral);

    // Left visual panel, right story text
    const panelW = 110;
    const panelH = 130;
    const panelX = M;
    const panelY = 48;
    drawSceneVisual(doc, panelX, panelY, panelW, panelH, page.visualTheme, page.visualCaption);

    const textX = M + panelW + 12;
    const textW = W - textX - M;
    if (i === 0 && page.heading) {
      drawText(doc, page.heading, textX, 56, textW, {
        size: 16, bold: true, color: C.navy,
      });
    } else if (i > 0) {
      drawText(doc, page.heading || 'What happens next…', textX, 56, textW, {
        size: 16, bold: true, color: C.navy,
      });
    }

    card(doc, textX, 66, textW, 112, C.warmYellow, 5);
    // Fit story body inside the card — overflow used to paint past the box and
    // look like a mid-name truncate ("…paintings. Ben") on the PDF.
    {
      const boxTop = 78;
      const boxBottom = 66 + 112 - 8;
      const maxH = boxBottom - boxTop;
      let size = 13;
      let lineH = 6.2;
      let fitted = [];
      const raw = String(page.text || '');
      while (size >= 9) {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(size);
        fitted = doc.splitTextToSize(strip(raw), textW - 16);
        lineH = size * 0.48;
        if (fitted.length * lineH <= maxH) break;
        size -= 1;
      }
      const maxLines = Math.max(1, Math.floor(maxH / Math.max(lineH, 4.5)));
      if (fitted.length > maxLines) {
        fitted = fitted.slice(0, maxLines);
        const last = fitted.length - 1;
        fitted[last] = String(fitted[last] || '').replace(/\s+$/, '') + '…';
      }
      ink(doc, C.dark);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(size);
      doc.text(fitted, textX + 8, boxTop, { maxWidth: textW - 16, lineHeightFactor: 1.35 });
    }

    drawText(doc, i === 0 ? 'Read together. Point to new words as you go.' : 'Finish the story. Check understanding as you read.', M, H - 16, W - 2 * M, {
      size: 9, italic: true, color: C.gray, align: 'center',
    });
  });

  // Pad to 2 pages if model only returned one
  if (pages.length === 1) {
    doc.addPage([W, H]);
    bg(doc, C.white);
    sectionHeader(doc, 'Story (cont.)', C.coral);
    drawText(doc, 'Continue discussing the story with your student.', M, 80, W - 2 * M, {
      size: 16, color: C.gray, align: 'center',
    });
  }
}

function pageComprehension(doc, lesson) {
  const questions = (lesson.story?.comprehensionQuestions || []).slice(0, 4);
  bg(doc, C.white);
  sectionHeader(doc, 'Reading Comprehension', C.blue);

  drawText(doc, 'Answer in complete sentences. Check the sample after the student answers.', M, 46, W - 2 * M, {
    size: 11, italic: true, color: C.gray, align: 'center',
  });

  const gap = Math.min(36, (H - 70) / Math.max(questions.length, 1));
  questions.forEach((q, i) => {
    const y = 56 + i * gap;
    card(doc, M, y, W - 2 * M, gap - 4, CARDS[i % CARDS.length], 4);
    fill(doc, DOTS[i % DOTS.length]);
    doc.circle(M + 10, y + 10, 4, 'F');
    drawText(doc, `${i + 1}. ${q.question}`, M + 18, y + 12, W - 2 * M - 28, {
      size: 13, bold: true, color: C.dark,
    });
    drawText(doc, `Sample: ${q.sampleAnswer}`, M + 18, y + 22, W - 2 * M - 28, {
      size: 11, italic: true, color: C.gray,
    });
  });
}

function pageCreative(doc, lesson) {
  const questions = (lesson.story?.creativeQuestions || []).slice(0, 2);
  bg(doc, C.mint);
  deco(doc, W - 25, 20, 40, C.green, 0.2);
  deco(doc, 10, H - 20, 35, C.green, 0.15);
  sectionHeader(doc, 'Your Ideas!', C.green);

  drawText(doc, 'Open-ended — there is no single right answer. Encourage creativity!', M, 48, W - 2 * M, {
    size: 12, italic: true, color: C.gray, align: 'center',
  });

  questions.forEach((q, i) => {
    const text = typeof q === 'string' ? q : (q && (q.question || q.prompt || q.text)) || '';
    if (!text) return;
    const y = 62 + i * 55;
    card(doc, M + 6, y, W - 2 * M - 12, 48, C.white, 6);
    fill(doc, DOTS[i % DOTS.length]);
    doc.circle(M + 20, y + 16, 5, 'F');
    drawText(doc, `Creative ${i + 1}`, M + 30, y + 18, W - 2 * M - 50, {
      size: 11, bold: true, color: C.gray,
    });
    drawText(doc, String(text), M + 18, y + 32, W - 2 * M - 40, {
      size: 16, bold: true, color: C.navy,
    });
  });

  drawText(doc, 'Give thinking time, then share answers out loud.', M, H - 16, W - 2 * M, {
    size: 9, italic: true, color: C.gray, align: 'center',
  });
}

function pagesSpeaking(doc, lesson) {
  const questions = lesson.speakingQuestions;
  const total = questions.length;

  questions.forEach((item, i) => {
    if (i > 0) doc.addPage([W, H]);
    bg(doc, C.white);
    sectionHeader(doc, "Let's Talk!", C.green);

    drawText(doc, `Question ${i + 1} of ${total}`, M, 50, W - 2 * M, {
      size: 11, color: C.gray, align: 'center',
    });

    const qY = 58;
    card(doc, M + 8, qY, W - 2 * M - 16, 42, C.lavender, 6);
    drawText(doc, item.question, M + 18, qY + 18, W - 2 * M - 36, {
      size: 22, bold: true, color: C.navy, align: 'center',
    });

    const aY = 115;
    drawText(doc, 'Sample Answer:', M + 16, aY, W - 2 * M - 32, {
      size: 11, bold: true, color: C.gray,
    });
    card(doc, M + 8, aY + 5, W - 2 * M - 16, 36, C.mint, 5);
    drawText(doc, item.sampleAnswer, M + 18, aY + 21, W - 2 * M - 36, {
      size: 17, italic: true, bold: true, color: [20, 120, 80], align: 'center',
    });

    drawText(doc, 'Wait for a complete-sentence answer before showing the sample.', M, H - 16, W - 2 * M, {
      size: 9, italic: true, color: C.gray, align: 'center',
    });
  });
}

function pageActivity(doc, lesson) {
  bg(doc, C.white);
  sectionHeader(doc, lesson.activity.title || 'Your Turn!', C.blue);

  drawText(doc, lesson.activity.prompt, M + 4, 50, W - 2 * M - 8, {
    size: 15, color: C.gray, align: 'center',
  });

  const templates = lesson.activity.templates.slice(0, 6);
  const gap = Math.min(22, (H - 80) / templates.length);

  templates.forEach((t, i) => {
    const y = 68 + i * gap;
    card(doc, M + 4, y, W - 2 * M - 8, gap - 4, CARDS[i % CARDS.length], 3);
    drawText(doc, `${i + 1}.  ${t}`, M + 14, y + (gap - 4) / 2 + 2, W - 2 * M - 28, {
      size: 17, bold: true, color: C.dark,
    });
  });

  drawText(doc, 'Guide the student through each template out loud.', M, H - 16, W - 2 * M, {
    size: 9, italic: true, color: C.gray, align: 'center',
  });
}

function pageWrapUp(doc, lesson) {
  bg(doc, C.blue);
  deco(doc, W - 30, -20, 55, C.navy, 0.22);
  deco(doc, -15, H - 10, 45, C.navy, 0.18);

  drawText(doc, 'Great Job!', M, 55, W - 2 * M, {
    size: 40, bold: true, color: C.white, align: 'center',
  });

  drawText(doc, "Today's Key Sentences:", M, 78, W - 2 * M, {
    size: 14, italic: true, color: [180, 210, 255], align: 'center',
  });

  const sentences = lesson.reviewSentences.slice(0, 4);
  sentences.forEach((r, i) => {
    const y = 98 + i * 20;
    drawText(doc, r, M + 20, y, W - 2 * M - 40, {
      size: 17, color: C.white, align: 'center',
    });
  });
}

// ── Main entry point ────────────────────────────────────────────────

async function buildLessonPdf(lesson, meta) {
  const jspdfNs = (typeof jspdf !== 'undefined' && jspdf)
    || (typeof window !== 'undefined' && window.jspdf)
    || null;
  const jsPDF = jspdfNs?.jsPDF
    || (typeof window !== 'undefined' && window.jsPDF)
    || null;
  if (!jsPDF) {
    throw new Error('jsPDF failed to load. Refresh the page and try again.');
  }

  if (typeof window !== 'undefined' && window.LessonPages && window.LessonPages.normalizeLesson) {
    lesson = window.LessonPages.normalizeLesson(lesson);
  }

  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'mm',
    format: [W, H],
  });

  pageTitleSlide(doc, lesson, meta);

  doc.addPage([W, H]);
  pageWarmUp(doc, lesson);

  doc.addPage([W, H]);
  await pagesVocabulary(doc, lesson);

  doc.addPage([W, H]);
  pageSentenceFrames(doc, lesson);

  doc.addPage([W, H]);
  pagesStory(doc, lesson);

  doc.addPage([W, H]);
  pageComprehension(doc, lesson);

  doc.addPage([W, H]);
  pageCreative(doc, lesson);

  doc.addPage([W, H]);
  pagesSpeaking(doc, lesson);

  doc.addPage([W, H]);
  pageActivity(doc, lesson);

  doc.addPage([W, H]);
  pageWrapUp(doc, lesson);

  const pageCount = doc.getNumberOfPages();
  const credit = (typeof window !== 'undefined' && window.VocabIcons && window.VocabIcons.CREDIT)
    || 'Twemoji by Twitter, Inc and other contributors';
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    drawText(doc, credit, M, H - 5, W - 2 * M, {
      size: 6, color: [160, 170, 180], align: 'center',
    });
  }

  const fileName = (lesson.title || 'Lesson').replace(/[^a-zA-Z0-9 ]/g, '').replace(/\s+/g, '-') + '.pdf';
  doc.save(fileName);

  return { pageCount, fileName };
}
